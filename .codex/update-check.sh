#!/usr/bin/env bash
# Хук SessionStart: подтягивает свежую версию инструмента в начале чата.
#
# Молчание — нормальный исход: нечего тянуть, нет сети, ветка не dev. Печатаем
# в stdout только когда агенту есть что сказать Менеджеру, и всегда выходим с
# кодом 0: сбой проверки обновлений не повод не дать человеку начать работу.
#
# Текст сообщений — без кавычек и обратных слэшей намеренно: он подставляется
# в JSON напрямую, и экранировать его нечем — ни python, ни jq на машине
# Менеджера не гарантированы.
#
# Логика живёт здесь, а не в .codex/hooks.json, специально. Codex привязывает
# доверие к хуку к содержимому конфигурации: правка hooks.json сбрасывает его
# в состояние «требует проверки», и до следующего похода Менеджера в настройки
# обновления молча перестают приходить. Строка вызова в hooks.json должна
# остаться неизменной навсегда; меняется этот файл.
set -uo pipefail

repo="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)" || exit 0
cd "$repo" || exit 0

say() {
  printf '{"hookSpecificOutput":{"hookEventName":"SessionStart","additionalContext":"%s"}}\n' "$1"
}

git rev-parse --git-dir >/dev/null 2>&1 || exit 0

# Только dev. На любой другой ветке сидит разработчик, и молча перематывать
# его работу на origin/dev нельзя.
[ "$(git rev-parse --abbrev-ref HEAD 2>/dev/null)" = "dev" ] || exit 0
git remote get-url origin >/dev/null 2>&1 || exit 0

# Зависшая сеть не должна задерживать старт чата: обрываем медленный обмен
# сами, не полагаясь на таймаут хука.
if ! git -c http.lowSpeedLimit=1000 -c http.lowSpeedTime=10 fetch --quiet origin dev 2>/dev/null; then
  exit 0
fi

behind="$(git rev-list --count HEAD..origin/dev 2>/dev/null)" || exit 0
[ -n "$behind" ] && [ "$behind" -gt 0 ] || exit 0

# Ничего принадлежащего Менеджеру в репозитории не хранится, поэтому местные
# правки отслеживаемых файлов откатываются. Неотслеживаемые файлы не трогаем:
# их мог положить сюда человек, и это единственное, что здесь может быть его.
reverted=""
if [ -n "$(git status --porcelain --untracked-files=no 2>/dev/null)" ]; then
  git checkout -- . 2>/dev/null && reverted=" Локальные изменения в файлах инструмента были отменены — предупреди об этом."
fi

if git merge --ff-only origin/dev >/dev/null 2>&1; then
  say "Инструмент обновлён: подтянуто новых изменений — $behind. Правила и скиллы читаются в начале чата, поэтому обновление вступит в силу только в следующем. Скажи Менеджеру об обновлении и предложи открыть New chat.$reverted"
else
  say "Автообновление инструмента не сработало: git не смог применить изменения. Скажи Менеджеру, что версия у него устаревшая, и предложи написать — обнови инструмент."
fi

exit 0
